"""Four supported speech languages. Claim processing continues to use English translations."""
from __future__ import annotations

import re
from collections import Counter

SUPPORTED = {'hi-IN': 'Hindi', 'en-IN': 'English', 'ml-IN': 'Malayalam', 'ta-IN': 'Tamil'}
STATE_LANGUAGES = {'madhya pradesh': 'hi-IN', 'tamil nadu': 'ta-IN', 'kerala': 'ml-IN'}


def code(value: str | None) -> str | None:
    if not isinstance(value, str):
        return None
    prefix = value.strip().lower().split('-')[0]
    return {'hi': 'hi-IN', 'en': 'en-IN', 'ml': 'ml-IN', 'ta': 'ta-IN'}.get(prefix)


def initial(state: str = '', district: str = '', override: str = '') -> str:
    if override and code(override):
        return code(override)
    if district.strip().lower() == 'sehore':
        return 'hi-IN'
    return STATE_LANGUAGES.get(state.strip().lower(), 'en-IN')


def script_language(text: str) -> str | None:
    counts = Counter()
    for char in text:
        if '\u0900' <= char <= '\u097f':
            counts['hi-IN'] += 1
        elif '\u0b80' <= char <= '\u0bff':
            counts['ta-IN'] += 1
        elif '\u0d00' <= char <= '\u0d7f':
            counts['ml-IN'] += 1
    return counts.most_common(1)[0][0] if counts else None


_NAMES = {'hi-IN': r'hindi|हिंदी|हिन्दी|இந்தி|ഹിന്ദി',
          'en-IN': r'english|अंग्रेजी|अंग्रेज़ी|ஆங்கிலம்|ഇംഗ്ലീഷ്',
          'ml-IN': r'malayalam|malyalam|मलयालम|மலையாளம்|മലയാളം',
          'ta-IN': r'tamil|तमिल|தமிழ்|തമിഴ്'}
_REQUEST = re.compile(r'speak|talk|use|switch|prefer|understand|know|language|in\b|बोल|समझ|भाषा|பேச|புரிய|மொழி|സംസാര|മനസ്സിലാ|ഭാഷ', re.I)
_NEGATIVE = re.compile(r"(?:don't|do not|cannot|can't|not|no)\s+(?:\w+\s+){0,3}$|नहीं|இல்லை|അല്ല|അറിയില്ല", re.I)
_COMPLAINT = re.compile(r"(?:don't|do not|cannot|can't|didn't|did not|couldn't|could not)\s+understand|not\s+understand|repeat|say (?:it|that) again|समझ.*नहीं|नहीं.*समझ|புரியவில்லை|மனസ്സிலായില്ല", re.I)


def requested(text: str) -> str | None:
    """Select the last positively requested language, ignoring 'I don't know Hindi'."""
    if not _REQUEST.search(text):
        return None
    matches = []
    for language, pattern in _NAMES.items():
        for match in re.finditer(pattern, text, re.I):
            prefix = text[max(0, match.start() - 45):match.start()]
            suffix = text[match.end():match.end() + 18]
            if _NEGATIVE.search(prefix) or re.match(r'\s*(?:नहीं|தெரியாது|അറിയില്ല)', suffix):
                continue
            matches.append((match.start(), language))
    return max(matches)[1] if matches else None


def choose(text: str, current: str, detected: str | None = None, confidence: float = 1.0) -> str:
    explicit = requested(text)
    if explicit:
        return explicit
    native = script_language(text)
    if native:
        return native
    source = code(detected)
    # English interjections are common inside all four languages. Do not oscillate on 'yes' or 'OK'.
    neutral = re.sub(r'[^a-z ]', '', text.lower()).strip() in {'yes', 'yes sir', 'no', 'no sir', 'okay', 'ok', 'hello', 'thank you'}
    if source and confidence >= 0.65 and not (source == 'en-IN' and neutral):
        return source
    return current


def repeat_request(text: str) -> bool:
    # A preference/complaint is not an answer to the current claim question.
    return requested(text) is not None or bool(_COMPLAINT.search(text))


